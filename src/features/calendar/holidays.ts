/** 해당 날짜의 표시 마크(공휴일·복날). 없으면 빈 배열. */
export function getDayMarks(dateYmd: string): DayMark[] {
  const out: DayMark[] = [];
  const h = HOLIDAYS[dateYmd];
  if (h) out.push({ name: h, kind: "holiday" });
  const b = BOKNAL[dateYmd];
  if (b) out.push({ name: b, kind: "bok" });
  return out;
}

/** 공휴일이면 true(날짜 숫자를 빨갛게 칠하는 용도). */
export function isHoliday(dateYmd: string): boolean {
  return dateYmd in HOLIDAYS;
}
