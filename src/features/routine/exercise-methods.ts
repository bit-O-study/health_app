/**
 * 운동법 단계 조회 — **서버 전용**.
 *
 * 확장 카탈로그 1,237개의 운동법 텍스트(350KiB)는 클라이언트 번들에서 뺐다.
 * 그 문장을 실제로 읽는 곳은 운동모드 큐를 만드는 서버 컴포넌트뿐이라,
 * 서버에서 필요한 항목만 붙여 props 로 내려보낸다.
 *
 * 기본 카탈로그는 자기 데이터(`EXERCISES[id].equipments[].method`)를,
 * 확장 카탈로그는 분리된 `EXTRA_METHODS` 를 본다. 없으면 빈 배열.
 */
export function methodSteps(
  exerciseId: string,
  equipment: EquipmentId,
): string[] {
  const reviewed = REVIEWED_RESISTANCE_METHODS[exerciseId];
  if (reviewed?.equipment === equipment) return reviewed.steps;
  if (equipment === "dumbbell" && exerciseId === "farmer-s-carry") {
    return [
      "양손에 덤벨을 하나씩 잡고 팔을 몸 옆으로 길게 내린다",
      "몸통을 곧게 세우고 짧고 일정한 보폭으로 앞으로 걷는다",
      "덤벨을 흔들거나 몸을 옆으로 기울이지 않고 양발을 번갈아 디딘다",
    ];
  }
  if (equipment === "kettlebell" && exerciseId === "kettlebell-swing") {
    return [
      "양발을 벌리고 케틀벨 하나의 손잡이를 양손으로 잡는다",
      "등을 곧게 유지하고 엉덩이를 뒤로 보내 케틀벨을 다리 사이로 보낸다",
      "엉덩이를 펴는 힘으로 케틀벨을 가슴에서 어깨 높이까지 보내고 다시 힌지한다",
    ];
  }
  if (equipment === "kettlebell" && exerciseId === "kettlebell-sumo-squat") {
    return [
      "양발을 골반너비보다 넓게 벌리고 발끝을 바깥으로 향한 뒤 케틀벨 하나를 양손으로 잡는다",
      "팔을 길게 두고 무릎을 발끝 방향으로 굽히며 케틀벨을 다리 사이로 내린다",
      "발 전체로 바닥을 밀어 일어서고 케틀벨을 휘두르지 않는다",
    ];
  }
  if (equipment === "bodyweight" && REVIEWED_BODYWEIGHT_METHODS[exerciseId]) {
    return REVIEWED_BODYWEIGHT_METHODS[exerciseId];
  }
  const base = EXERCISES[exerciseId]?.equipments.find(
    (v) => v.equipment === equipment,
  )?.method;
  if (base && base.length > 0) return base;
  // 확장 카탈로그는 틀 문장이라 "바벨을(를)" 같은 조사가 남아 있다 — 보여 주기 전에 다듬는다.
  return (EXTRA_METHODS[exerciseId]?.[equipment] ?? []).map(cleanMethodText);
}

/** 이 운동에 (어느 기구로든) 운동법 단계가 있는지 — 안내 노출 판단용. */
export function hasMethodSteps(exerciseId: string): boolean {
  const base = EXERCISES[exerciseId]?.equipments.some(
    (v) => (v.method?.length ?? 0) > 0,
  );
  if (base) return true;
  const extra = EXTRA_METHODS[exerciseId];
  return extra ? Object.values(extra).some((s) => s.length > 0) : false;
}
