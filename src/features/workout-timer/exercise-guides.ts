export function guideFor(exerciseId: string): ExerciseGuide {
  const base =
    EXERCISE_GUIDES[exerciseId] ??
    FALLBACK_BY_CATEGORY[motionCategoryFor(exerciseId)];
  const proTips = EXERCISE_PRO_TIPS[exerciseId];
  const setupSteps = EXERCISE_SETUP_STEPS[exerciseId];
  if (!proTips && !setupSteps) return base;
  return {
    ...base,
    ...(proTips ? { proTips } : {}),
    ...(setupSteps ? { setupSteps } : {}),
  };
}

