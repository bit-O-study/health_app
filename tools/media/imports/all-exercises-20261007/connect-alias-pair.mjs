import {readFileSync,writeFileSync} from 'node:fs';
const methodPath='src/features/routine/exercise-catalog-extra-methods.ts';
let methods=readFileSync(methodPath,'utf8');
const pattern=id=>new RegExp('  "'+id+'": \\{[\\s\\S]*?\\n  \\},');
const steps=['서서 덤벨을 오버핸드 그립으로 잡고 손바닥이 뒤를 향하게 한다','상완을 몸 옆에 고정하고 손목을 곧게 유지하며 팔꿈치를 굽혀 올린다','손바닥 방향을 유지하며 반동 없이 덤벨을 천천히 내린다'];
for(const id of ['dumbbell-reverse-curl','pronated-dumbbell-curl'])methods=methods.replace(pattern(id),`  "${id}": {\n    "dumbbell": ${JSON.stringify(steps,null,6)}\n  },`);
const wrist=methods.match(pattern('reverse-wrist-curl'))?.[0];
if(!wrist)throw Error('Missing wrist source');
methods=methods.replace(pattern('dumbbell-wrist-extension'),wrist.replace('"reverse-wrist-curl"','"dumbbell-wrist-extension"'));
writeFileSync(methodPath,methods);
const guidePath='src/features/workout-timer/exercise-guides.ts';
let guides=readFileSync(guidePath,'utf8');
const wristGuide=guides.match(pattern('reverse-wrist-curl'))?.[0];
if(!wristGuide)throw Error('Missing wrist guide');
const guide={setup:steps[0],targets:[{name:'상완요골근·이두근',feel:'팔뚝 바깥쪽과 팔 앞쪽이 수축하는 느낌'}],cues:steps.slice(1),beginnerTips:['손목을 꺾거나 손바닥을 위로 돌리지 말고 가벼운 무게로 시작하세요.']};
const entries=['dumbbell-reverse-curl','pronated-dumbbell-curl'].map(id=>`  "${id}": ${JSON.stringify(guide,null,4)},`).join('\n');
guides=guides.replace('const EXERCISE_GUIDES: Record<string, ExerciseGuide> = {','$&\n'+entries+'\n'+wristGuide.replace('"reverse-wrist-curl"','"dumbbell-wrist-extension"'));
guides=guides.replace('const EXERCISE_ONE_LINER: Record<string, string> = {','$&\n  "dumbbell-reverse-curl": "오버핸드 그립으로 상완을 고정하고 덤벨을 말아 올리세요.",\n  "pronated-dumbbell-curl": "오버핸드 그립으로 상완을 고정하고 덤벨을 말아 올리세요.",\n  "dumbbell-wrist-extension": "전완을 허벅지에 받치고 손바닥을 아래로 유지하며 손목만 펴세요.",');
writeFileSync(guidePath,guides);
