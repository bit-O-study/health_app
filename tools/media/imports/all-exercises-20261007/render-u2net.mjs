import {copyFileSync,mkdirSync,readFileSync,writeFileSync} from 'node:fs';
import {resolve,join} from 'node:path';
import {pathToFileURL} from 'node:url';
import {freemem} from 'node:os';
const id=process.argv[2];
if(!['lying-triceps-extension','ez-bar-skull-crusher'].includes(id))throw Error('Unexpected candidate id');
const variant=process.argv[3]??'';if(!['','-refined'].includes(variant))throw Error('Unexpected variant');
const project=resolve('.'),out=join(project,'tools/media/imports/all-exercises-20261007/u2net',id+variant);
if(freemem()<4*1024**3)throw Error('Insufficient free memory for another candidate');
const guides=join(out,'tools/media/motion-guides');mkdirSync(guides,{recursive:true});mkdirSync(join(out,'tools/media/ai-guides'),{recursive:true});
const catalog=JSON.parse(readFileSync('tools/media/ai-guides/catalog.json','utf8'));
writeFileSync(join(out,'tools/media/ai-guides/catalog.json'),JSON.stringify(catalog.filter(x=>x.id===id)));
copyFileSync('tools/media/motion-guides/'+id+'.jpg',join(guides,id+'.jpg'));
const spec=JSON.parse(readFileSync('tools/media/motion-guides/'+id+'.json','utf8'));
if(spec.renderer)throw Error('Custom renderer needs separate handling');
writeFileSync(join(guides,id+'.json'),JSON.stringify({...spec,cutout:true},null,2));
process.env.MOTION_CUTOUT_MODEL='u2net';process.env.U2NET_HOME=join(project,'tools/media/imports/cutout-models');process.env.OMP_NUM_THREADS='2';
process.env.MOTION_CUTOUT_PYTHON='C:/git/Bit-O/video-tools/python312/python.exe';
process.env.PATH='C:/git/Bit-O/video-tools/ffmpeg/ffmpeg-9.0.2-essentials_build/bin;'+process.env.PATH;
const started=Date.now();process.chdir(out);
const {manageMotionGuides}=await import(pathToFileURL(join(project,'tools/media/manage-motion-guides.mjs')));
await manageMotionGuides('motion-build',id);
writeFileSync(join(out,'benchmark.json'),JSON.stringify({id,model:'u2net',started,finished:Date.now(),seconds:(Date.now()-started)/1000,published:false},null,2));
